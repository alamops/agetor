/**
 * Recording variant of a fake tmux bin — copied from
 * claude-tmux-queue.test.ts (not exported from that file, so duplicated
 * here). Writes a small bun script as the tmux bin that appends one
 * `{ ns, argv }` JSON line per invocation to a log file, so tests can assert
 * both the order and content of tmux calls without a real tmux server.
 */
function withRecordingTmuxBin<T>(fn: (logPath: string) => Promise<T>): Promise<T> {
  const dir = mkdtempSync(path.join(tmpdir(), "agetor-tmux-rec-"));
  const binPath = path.join(dir, "tmux");
  const logPath = path.join(dir, "log.jsonl");
  writeFileSync(
    binPath,
    `#!${process.execPath}\n` +
      `import { appendFileSync } from "node:fs";\n` +
      `appendFileSync(${JSON.stringify(logPath)}, JSON.stringify({ ms: Date.now(), argv: process.argv.slice(2) }) + "\\n");\n`,
  );
  chmodSync(binPath, 0o755);
  const prevBin = process.env.AGETOR_TMUX_BIN;
  process.env.AGETOR_TMUX_BIN = binPath;
  return fn(logPath).finally(() => {
    if (prevBin === undefined) delete process.env.AGETOR_TMUX_BIN;
    else process.env.AGETOR_TMUX_BIN = prevBin;
  });
}

function readTmuxLog(logPath: string): Array<{ ms: number; argv: string[] }> {
  let raw: string;
  try {
    raw = readFileSync(logPath, "utf8");
  } catch {
    return [];
  }
  return raw.split("\n").filter(Boolean).map((l) => JSON.parse(l)).map((entry) => {
    // Every tmux spawn leads with tmuxSocketArgs() (["-L", <name>]) under
    // `bun test` — strip that pair so send-keys assertions here don't have
    // to know about socket isolation. Mirrors claude-tmux-queue.test.ts.
    const [a, , ...rest] = entry.argv;
    return a === "-L" ? { ...entry, argv: rest } : entry;
  });
}

/**
 * Lightweight tmux stub for tests that only need the underlying
 * `Bun.spawnSync` calls to succeed — no argv log, no per-invocation bun
 * cold-start. `/usr/bin/true` works on both macOS and most Linux distros
 * (mirrors claude-tmux-queue.test.ts's `FAKE_TMUX_BIN`). Prefer this over
 * `withRecordingTmuxBin` whenever a test doesn't actually inspect the tmux
 * call log.
 */
function withFakeTmuxBin<T>(fn: () => Promise<T>): Promise<T> {
  const prevBin = process.env.AGETOR_TMUX_BIN;
  process.env.AGETOR_TMUX_BIN = "/usr/bin/true";
  return fn().finally(() => {
    if (prevBin === undefined) delete process.env.AGETOR_TMUX_BIN;
    else process.env.AGETOR_TMUX_BIN = prevBin;
  });
}

