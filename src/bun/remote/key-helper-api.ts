/**
 * The key helper as the gateway sees it (docs/plans/remote-readiness.md §3.3, spec "Keys and cryptography", grill D2, D3, D4).
 *
 * The helper is a signed Swift `.app` (native/keyhelper/) and the only process that can use the core session key (X25519, in its
 * data-protection keychain item) and the registry key (P-256, in the Secure Enclave). Bun asks it for exactly one Diffie-Hellman
 * per handshake, for the registry public key and revocation list, for revoke, and to run the native pairing window. There is no
 * login-keychain fallback: without the helper, a Secure Enclave or the keychain item, the gateway refuses to pair.
 *
 * `getKeyHelper()` returns the real client, or, only outside a release build and only under a test seam, the fake. The seam is
 * compiled out of release bundles (docs/architecture/testing-seams.md, `src/shared/build-flags.ts`).
 */
import type { RemoteLevel } from "@agetor/remote-protocol/levels";
import { remoteSeamsAllowed } from "../../shared/build-flags.ts";

export type KeyHelperErrorCode =
  | "helper-missing"
  | "helper-crashed"
  | "timeout"
  | "no-secure-enclave"
  | "keychain-unavailable"
  | "wrong-code"
  | "expired"
  | "cancelled"
  | "auth-failed"
  | "busy"
  | "bad-args"
  | "bad-json"
  | "line-too-long"
  | "unknown-command"
  | "internal"
  | "closed";

export class KeyHelperError extends Error {
  constructor(
    readonly code: KeyHelperErrorCode,
    message?: string,
  ) {
    super(message ?? code);
    this.name = "KeyHelperError";
  }
}

export interface KeyHelperStatus {
  version: string;
  secureEnclave: true;
  /** The core session key's public half (X25519, 32 bytes). Part of the QR code and the Noise prologue's core id. */
  corePub: Uint8Array;
  /** The registry key's public half (P-256 uncompressed, 65 bytes). Verifies every device entry's signature. */
  registryPub: Uint8Array;
}

export interface PairBeginArgs {
  relayUrl: string;
  macName: string;
  expiresAt: number;
}

export interface PairBeginResult {
  /** 32 random bytes: the pre-shared key of the pairing handshake. Single use, expires with the window. */
  pairingSecret: Uint8Array;
  /** The QR payload (base64url canonical JSON, `packages/remote-protocol/src/qr.ts`) the helper drew. */
  qr: string;
}

export interface PairCompleteArgs {
  handshakeHash: Uint8Array;
  /** 32 lowercase hex characters, generated by the core. */
  deviceId: string;
  /** Already cleaned by the core; the helper draws it as plain text. */
  name: string;
  platform: "ios" | "android";
  appVersion: string;
  sessionPub: Uint8Array;
  approvePub: Uint8Array;
  pushPub: Uint8Array;
  enrolledAt: number;
}

export interface PairCompleteResult {
  /** The level the owner chose in the window (Respond preselected; Configure needs a second confirmation). The signature covers it. */
  level: RemoteLevel;
  /** The canonical JSON the registry key signed. The core re-derives it and compares before storing. */
  entry: string;
  /** Raw ES256 `r‖s`, 64 bytes. */
  sig: Uint8Array;
}

export type KeyHelperEvent = "window-closed" | "pairing-cancelled";

export interface KeyHelper {
  status(): Promise<KeyHelperStatus>;
  /** One X25519 Diffie-Hellman with the core static key. The private key never leaves the helper. */
  dh(peerPub: Uint8Array): Promise<Uint8Array>;
  /** The helper's own append-only revoked list (device ids). */
  revoked(): Promise<string[]>;
  revoke(id: string): Promise<string[]>;
  /** Revoke every id the helper ever signed, then replace the core key. Every phone must pair again. */
  revokeAll(): Promise<{ ids: string[]; corePub: Uint8Array }>;
  /** Open the native pairing window with its QR code. Resolves when the window is up. */
  pairBegin(args: PairBeginArgs): Promise<PairBeginResult>;
  /** Hand the phone's hash, keys and name to the window and wait for the code, the level and Touch ID. */
  pairComplete(args: PairCompleteArgs): Promise<PairCompleteResult>;
  pairCancel(): Promise<void>;
  onEvent(fn: (e: KeyHelperEvent) => void): () => void;
  close(): void;
}

let current: KeyHelper | null = null;

/**
 * The process-wide helper: the fake iff the seam guard allows it AND `AGETOR_FAKE_KEY_HELPER=1`; otherwise the real client.
 * The inline `__AGETOR_RELEASE_BUILD__` condition is what lets a release bundle drop the fake module entirely
 * (`src/shared/build-flags.ts`: the expression must be inline for the bundler to fold it).
 */
export function getKeyHelper(): KeyHelper {
  if (current) return current;
  if (
    !(typeof __AGETOR_RELEASE_BUILD__ !== "undefined" && __AGETOR_RELEASE_BUILD__) &&
    remoteSeamsAllowed(process.env) &&
    process.env.AGETOR_FAKE_KEY_HELPER === "1"
  ) {
    const fake = require("./key-helper-fake.ts") as typeof import("./key-helper-fake.ts");
    current = fake.createFakeKeyHelper();
  } else {
    const real = require("./key-helper.ts") as typeof import("./key-helper.ts");
    current = real.createRealKeyHelper();
  }
  return current;
}

/** Replace (or clear, with null) the process-wide helper: gateway tests inject a fake or a spy. Closes the one it replaces. */
export function setKeyHelperForTests(helper: KeyHelper | null): void {
  const prev = current;
  current = helper;
  if (prev && prev !== helper) prev.close();
}
